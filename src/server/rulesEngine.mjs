import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const RULES_PATH = path.resolve(__dirname, '../config/rules.json');

export function getRules() {
  if (!fs.existsSync(RULES_PATH)) {
    throw new Error('Critical: src/config/rules.json missing.');
  }
  return JSON.parse(fs.readFileSync(RULES_PATH, 'utf8'));
}

export function generateCssTokens() {
  const rules = getRules();
  const dark = rules.designSystem.colorTokens.dark;
  const light = rules.designSystem.colorTokens.light;
  const geo = rules.designSystem.geometry;
  const opt = rules.designSystem.optical;

  return `
/* AUTOGENERATED FROM src/config/rules.json - DO NOT MANUALLY OVERRIDE */
:root {
  --radius-capsule: ${geo.radiusCapsule};
  --radius-cell: ${geo.radiusCell};
  --radius-card: ${geo.radiusCard};
  --glass-blur: ${opt.blur};
  --glass-saturate: ${opt.saturate};
  --time-fast: ${opt.transitionFast};
  --time-smooth: ${opt.transitionSmooth};
}

[data-theme="dark"] {
  --bg-core: ${dark.bgCore};
  --bg-surface: ${dark.bgSurface};
  --text-primary: ${dark.textPrimary};
  --text-secondary: ${dark.textSecondary};
  --text-tertiary: ${dark.textTertiary};
  --glass-fill: ${dark.glassFill};
  --glass-fill-hover: ${dark.glassFillHover};
  --glass-border: ${dark.glassBorder};
  --glass-specular: ${dark.glassSpecular};
  --glass-shadow: ${dark.glassShadow};
}

[data-theme="light"] {
  --bg-core: ${light.bgCore};
  --bg-surface: ${light.bgSurface};
  --text-primary: ${light.textPrimary};
  --text-secondary: ${light.textSecondary};
  --text-tertiary: ${light.textTertiary};
  --glass-fill: ${light.glassFill};
  --glass-fill-hover: ${light.glassFillHover};
  --glass-border: ${light.glassBorder};
  --glass-specular: ${light.glassSpecular};
  --glass-shadow: ${light.glassShadow};
}
  `.trim();
}